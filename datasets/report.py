"""Generate human-readable summary reports for prepared datasets.

Creates a Markdown report describing the dataset:
- Location and time range
- Variables and models included
- Data volumes (row counts, file sizes)
- Event summary (counts per event type)
- Metric highlights (best/worst performance)
- Provenance and attribution

Output: reports/report.md inside the dataset directory.

Usage
-----
>>> from datasets.report import generate_report

>>> report_path = generate_report(
...     manifest,
...     data_dir="./datasets/copenhagen_2y",
...     output_path="./datasets/copenhagen_2y/reports/report.md",
... )
"""

from __future__ import annotations

import logging
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


def generate_report(
    manifest: dict[str, Any],
    data_dir: str | Path,
    output_path: str | Path | None = None,
) -> str:
    """Generate a human-readable Markdown report.

    Args:
        manifest: Dataset manifest dictionary.
        data_dir: Dataset root directory.
        output_path: Optional explicit output path. If None, uses
            {data_dir}/reports/report.md.

    Returns:
        Generated report string.
    """
    data_dir = Path(data_dir)
    if output_path is None:
        output_path = data_dir / "reports" / "report.md"
    else:
        output_path = Path(output_path)

    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Collect stats
    stats = manifest.get("statistics", {})
    prov = manifest.get("provenance", {})
    loc = manifest.get("location", {})
    time_range = manifest.get("time_range", {})
    pipeline = manifest.get("pipeline", {})

    # Compute file sizes
    total_size = 0
    file_count = 0
    for root, dirs, files in os.walk(data_dir):
        for f in files:
            if f.endswith(".parquet"):
                fp = Path(root) / f
                total_size += fp.stat().st_size
                file_count += 1

    size_mb = total_size / (1024 * 1024)

    # Build report sections
    report = f"""# Dataset Report: {manifest.get("dataset_name", "unknown")}

## Overview

| Field | Value |
|-------|-------|
| **Location** | {loc.get("name", "N/A")} ({loc.get('latitude', 'N/A')}°, {loc.get('longitude', 'N/A')}°) |
| **Time Range** | {time_range.get('start_date', 'N/A')} to {time_range.get('end_date', 'N/A')} |
| **Variables** | {', '.join(manifest.get('variables', []))} |
| **Models** | {', '.join(manifest.get('models', []))} |
| **Version** | {manifest.get('version', 'N/A')} |
| **Pipeline Version** | {manifest.get('pipeline_version', 'N/A')} |
| **Generated** | {manifest.get('generated_at', 'N/A')} |

## Data Volumes

| Type | Rows | Size |
|------|------|------|
| Forecasts | {stats.get('forecast_rows', 0):,} | — |
| Observations | {stats.get('observation_rows', 0):,} | — |
| Verification | {stats.get('verification_rows', 0):,} | — |
| **Total parquet files** | | **{file_count:,} files ({size_mb:.1f} MB)** |

## Precomputed Metrics

"""

    for group in stats.get("metric_groups", []):
        group_dir = data_dir / "metrics" / group
        if group_dir.exists():
            file_count_group = len(list(group_dir.glob("*.parquet")))
            report += f"- **{group.replace('_', ' ').title()}**: {file_count_group} file(s)\n"
        else:
            report += f"- **{group.replace('_', ' ').title()}**: not computed\n"

    report += "\n## Precomputed Events\n\n"

    for event in stats.get("event_datasets", []):
        event_dir = data_dir / "events" / event
        if event_dir.exists():
            event_files = list(event_dir.glob("*.parquet"))
            report += f"- **{event}**: {len(event_files)} file(s)\n"
        else:
            report += f"- **{event}**: not computed\n"

    report += "\n## Attribution\n\n"
    report += f"""**Forecast data:** {prov.get('forecast_source', 'N/A')} — [{prov.get('license', 'N/A')}]
**Observation data:** {prov.get('observation_source', 'N/A')} — [{prov.get('license', 'N/A')}]

---

*Report generated by weather_forecast_analyzer_v2 {manifest.get('pipeline_version', '?')} on {datetime.now(timezone.utc).isoformat()}*
"""

    # Write to file
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(report)

    logger.info("Wrote report: %s", output_path)
    return report
